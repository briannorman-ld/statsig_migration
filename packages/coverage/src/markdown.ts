/**
 * Renders the coverage matrix as Markdown for docs/LIMITATIONS.md. The doc keeps hand-written
 * narrative around a generated block delimited by the markers below; `pnpm coverage:generate`
 * rewrites only the block, and a test fails when the committed block is stale.
 */
import { AREAS, COVERAGE, countByStatus } from './matrix.ts';
import type { CoverageEntry, CoverageStatus } from './types.ts';

export const BLOCK_START = '<!-- coverage:start (generated by pnpm coverage:generate; edit packages/coverage/src/matrix.ts) -->';
export const BLOCK_END = '<!-- coverage:end -->';

export const STATUS_LABEL: Record<CoverageStatus, string> = {
  migrates: 'Migrates',
  decisions: 'Migrates with decisions',
  guided: 'Guided / manual',
  planned: 'Planned',
  none: 'No LD equivalent',
};

export const STATUS_MARK: Record<CoverageStatus, string> = {
  migrates: '✅',
  decisions: '🟡',
  guided: '🧭',
  planned: '🚧',
  none: '❌',
};

export const STATUS_DESCRIPTION: Record<CoverageStatus, string> = {
  migrates: 'Translated exactly and written automatically; at most an informational note.',
  decisions: 'Written automatically once you answer a Decision or acknowledge a documented difference. Nothing is dropped silently.',
  guided: 'The console does not write it; it produces a checklist, a generated document or step-by-step guidance and a person finishes it in LD or in code.',
  planned: 'LD has an equivalent and the mapping is specified, but the console does not write it yet. The item is inventoried and its blockers are listed.',
  none: 'LaunchDarkly has no equivalent, or it is a different product that is set up on its own.',
};

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

function docLinks(e: CoverageEntry): string {
  const links: string[] = [];
  if (e.docs?.statsig) links.push(`[StatSig](${e.docs.statsig})`);
  if (e.docs?.ld) links.push(`[LD](${e.docs.ld})`);
  return links.join(' · ');
}

function details(e: CoverageEntry): string {
  const parts: string[] = [];
  if (e.detail) parts.push(e.detail);
  if (e.decisions?.length) parts.push(`Decisions: ${e.decisions.map((d) => `\`${d}\``).join(', ')}.`);
  if (e.edgeCases?.length) parts.push(`Edge cases: ${e.edgeCases.join(', ')}.`);
  const links = docLinks(e);
  if (links) parts.push(links);
  return parts.join(' ');
}

export function renderCoverageMarkdown(entries: readonly CoverageEntry[] = COVERAGE): string {
  const counts = countByStatus(entries);
  const out: string[] = [BLOCK_START, ''];
  out.push('### Legend', '');
  out.push('| Mark | Status | Meaning | Rows |', '|---|---|---|---|');
  for (const s of ['migrates', 'decisions', 'guided', 'planned', 'none'] as const) {
    out.push(`| ${STATUS_MARK[s]} | **${STATUS_LABEL[s]}** | ${STATUS_DESCRIPTION[s]} | ${counts[s]} |`);
  }
  out.push('');
  for (const a of AREAS) {
    const rows = entries.filter((e) => e.area === a.area);
    if (!rows.length) continue;
    out.push(`### ${a.title}`, '', a.summary, '');
    out.push('| | StatSig | LaunchDarkly | How the console handles it | Notes |', '|---|---|---|---|---|');
    for (const e of rows) {
      out.push(`| ${STATUS_MARK[e.status]} | ${cell(e.statsig)} | ${cell(e.ld)} | ${cell(e.how)} | ${cell(details(e))} |`);
    }
    out.push('');
  }
  out.push(BLOCK_END);
  return out.join('\n');
}

/** Replaces the generated block inside a document; appends one when the markers are missing. */
export function spliceCoverageBlock(doc: string, block: string = renderCoverageMarkdown()): string {
  const start = doc.indexOf(BLOCK_START);
  const end = doc.indexOf(BLOCK_END);
  if (start === -1 || end === -1 || end < start) return `${doc.trimEnd()}\n\n${block}\n`;
  return `${doc.slice(0, start)}${block}${doc.slice(end + BLOCK_END.length)}`;
}
