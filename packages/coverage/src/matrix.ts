/** Workspace-free statistics for the summary strip. */
export function countByStatus(entries: readonly CoverageEntry[] = COVERAGE): Record<CoverageEntry['status'], number> {
  const out = { migrates: 0, decisions: 0, guided: 0, planned: 0, none: 0 };
  for (const e of entries) out[e.status]++;
  return out;
}
